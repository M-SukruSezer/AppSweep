_NORM = re.compile(r"[^a-z0-9]+")


def _norm(s: str) -> str:
    return _NORM.sub("", s.lower())


def _is_candidate_name(name: str) -> bool:
    """Whether a directory name is specific enough to attribute at all.

    Names under three characters are rejected. A directory called ``rg`` or
    ``fd`` may well belong to ripgrep or fd-find, but it may equally belong
    to anything else, and there is no way to tell from the name. AppSweep
    would rather miss those than guess at them, so such directories are
    never offered for removal.
    """
    if name in KNOWN_SAFE or name.lstrip(".") in KNOWN_SAFE:
        return False
    if name.lower() in SHARED_NAMES:
        return False
    return len(name.lstrip(".")) >= 3


def _score(dirname: str, tokens: list[str]) -> tuple[int, str]:
    """How strongly ``dirname`` looks like it belongs to ``tokens``.

    Returns (score, matched_token). Higher is better; 0 means no match.
    """
    bare = dirname.lstrip(".")
    nd = _norm(bare)
    if not nd:
        return 0, ""
    best = (0, "")
    for tok in tokens:
        nt = _norm(tok)
        if len(nt) < 3:
            continue
        if nd == nt:
            return 100, tok                       # exact: unambiguous
        # reverse-dns app ids: org.gnome.Loupe vs loupe
        if "." in dirname and dirname.lower().endswith("." + tok.lower()):
            return 95, tok
        if nd.startswith(nt) and len(nt) >= 4:
            cand = (70 + min(len(nt), 20), tok)
        elif nt.startswith(nd) and len(nd) >= 5:
            cand = (55 + min(len(nd), 20), tok)
        elif len(nt) >= 6 and nt in nd:
            cand = (40, tok)
        else:
            continue
        if cand[0] > best[0]:
            best = cand
    return best


def _confidence(score: int) -> str:
    if score >= 95:
        return "high"
    if score >= 70:
        return "medium"
    return "low"


def _walk_roots() -> list[tuple[str, str, bool]]:
    """Every direct child of every root. (path, kind, needs_root)"""
    out: list[tuple[str, str, bool]] = []
    for root, kind, needs_root in ROOTS:
        try:
            with os.scandir(root) as it:
                for e in it:
                    try:
                        if e.is_symlink() or not e.is_dir(follow_symlinks=False):
                            continue
                    except OSError:
                        continue
                    if root == str(HOME) and not e.name.startswith("."):
                        continue
                    if not _is_candidate_name(e.name):
                        continue
                    out.append((e.path, kind, needs_root))
        except OSError:
            continue
    return out


def _installed_token_index(installed: list[App]) -> list[tuple[str, list[str]]]:
    return [(a.key, a.tokens) for a in installed if a.tokens]


def scan_for(
    app: App,
    installed: list[App],
    *,
    min_score: int = 70,
    with_sizes: bool = True,
) -> list[Residue]:
    """Leftovers attributable to ``app`` and to nothing still installed."""
    others = [
        (key, toks) for key, toks in _installed_token_index(installed)
        if key != app.key
    ]
    found: list[Residue] = []
    for path, kind, needs_root in _walk_roots():
        name = os.path.basename(path)
        score, token = _score(name, app.tokens)
        if score < min_score:
            continue
        # Does something still installed explain this better?
        rival = max((_score(name, toks)[0] for _, toks in others), default=0)
        if rival >= score:
            continue
        if needs_root and _owned_by_a_package(path):
            continue          # still owned by an installed package
        if not is_safe(path):
            continue
        found.append(
            Residue(
                path=path,
                size_bytes=dir_size(path) if with_sizes else 0,
                kind=kind,
                matched_token=token,
                confidence=_confidence(score),
                needs_root=needs_root,
            )
        )
    found.sort(key=lambda r: (-r.size_bytes, r.path))
    return found


def scan_unclaimed(
    installed: list[App],
    *,
    include_cache: bool = False,
    include_system: bool = True,
    with_sizes: bool = True,
) -> list[Residue]:
    """Directories no installed app accounts for.

    These are the real long-term accumulation: settings from software
    uninstalled months ago. Confidence is never better than "medium" here,
    because absence of a match is weaker evidence than a positive one.
    """
    index = _installed_token_index(installed)
    desktop = _desktop_tokens()
    out: list[Residue] = []
    for path, kind, needs_root in _walk_roots():
        if kind == "cache" and not include_cache:
            continue
        if kind == "system" and not include_system:
            continue
        name = os.path.basename(path)
        best = max((_score(name, toks)[0] for _, toks in index), default=0)
        if best >= 55:
            continue
        if max((_score(name, [t])[0] for t in desktop), default=0) >= 70:
            continue
        if needs_root and _owned_by_a_package(path):
            continue
        if not is_safe(path):
            continue
        # A system directory with no name match is the weakest evidence
        # there is: plenty of packages create /etc and /var/lib directories
        # whose names look nothing like the package name. Never rate those
        # above "low", so the UI cannot pre-select them.
        conf = "medium" if best == 0 else "low"
        if needs_root:
            conf = "low"
        out.append(
            Residue(
                path=path,
                size_bytes=dir_size(path) if with_sizes else 0,
                kind=kind,
                matched_token="",
                confidence=conf,
                needs_root=needs_root,
            )
        )
    out.sort(key=lambda r: (-r.size_bytes, r.path))
    return out


_owned_cache: dict[str, bool] = {}


def _owned_by_a_package(path: str) -> bool:
    """True when the distro's package database still claims ``path``."""
    if path in _owned_cache:
        return _owned_cache[path]
    owned = False
    if have("dpkg-query"):
        res = run(["dpkg-query", "-S", path], timeout=20)
        owned = res.ok and bool(res.out.strip())
    elif have("rpm"):
        res = run(["rpm", "-qf", path], timeout=20)
        owned = res.ok
    elif have("pacman"):
        res = run(["pacman", "-Qoq", path], timeout=20)
        owned = res.ok and bool(res.out.strip())
    _owned_cache[path] = owned
    return owned


def _desktop_tokens() -> list[str]:
    """Names of every installed launcher, so active apps are never flagged."""
    toks: set[str] = set()
    dirs = [
        "/usr/share/applications",
        "/usr/local/share/applications",
        "/var/lib/flatpak/exports/share/applications",
        str(HOME / ".local/share/applications"),
        str(HOME / ".local/share/flatpak/exports/share/applications"),
        "/var/lib/snapd/desktop/applications",
    ]
    for d in dirs:
        try:
            entries = os.listdir(d)
        except OSError:
            continue
        for fn in entries:
            if fn.endswith(".desktop"):
                stem = fn[: -len(".desktop")]
                toks.add(stem)
                toks.add(stem.rsplit(".", 1)[-1])
                toks.add(stem.split("_")[0])
    return [t for t in toks if len(t) >= 3]


def total_size(residues: list[Residue]) -> int:
    return sum(r.size_bytes for r in residues)


def fill_sizes(residues: list[Residue]) -> None:
    for r in residues:
        if r.size_bytes == 0:
            r.size_bytes = dir_size(r.path)


def trash_or_delete(path: str, *, permanent: bool = False) -> tuple[bool, str]:
    """Move ``path`` to the trash, or delete it. Always safety-checked."""
    from .safety import Unsafe, check_path, check_shape

    # Permissibility first: a protected path must be refused whether or not
    # it happens to exist right now.
    try:
        check_shape(path)
    except Unsafe as exc:
        return False, f"refused: {exc}"

    if not os.path.lexists(path):
        # The uninstall command may already have taken it (flatpak
        # --delete-data, apt purge). Not an error.
        return True, "already gone"

    try:
        p = check_path(path)
    except Unsafe as exc:
        return False, f"refused: {exc}"

    if not permanent and have("gio"):
        res = run(["gio", "trash", str(p)], timeout=60)
        if res.ok:
            return True, "moved to trash"
        return False, (res.err or "gio trash failed").strip()

    import shutil

    try:
        if p.is_dir():
            shutil.rmtree(p)
        else:
            p.unlink()
    except OSError as exc:
        return False, str(exc)
    return True, "deleted"
