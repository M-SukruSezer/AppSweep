"""Find configuration, data and cache left behind by software.

Two modes:

``scan_for(app, installed)``
    Leftovers belonging to one app. Used right after an uninstall.

``scan_unclaimed(installed)``
    Directories under the standard locations that no *currently installed*
    app accounts for — residue from software removed long ago, including
    software removed before AppSweep existed.

Both modes attribute by name, which is a heuristic, so every result carries
a confidence level and the caller is expected to make the user confirm.
A candidate is dropped whenever a still-installed app explains it better
than the app being removed: that is what stops AppSweep from deleting
``~/.config/google-chrome`` while uninstalling ``chrome-gnome-shell``.
"""
from __future__ import annotations

import os
import re
from pathlib import Path

from .models import App, Residue
from .safety import HOME, SHARED_NAMES, is_safe
from .util import dir_size, have, run

#: (directory, kind, needs_root)
ROOTS: tuple[tuple[str, str, bool], ...] = (
    (str(HOME / ".config"), "config", False),
    (str(HOME / ".local/share"), "data", False),
    (str(HOME / ".local/state"), "state", False),
    (str(HOME / ".cache"), "cache", False),
    (str(HOME / ".var/app"), "data", False),
    (str(HOME), "config", False),          # dotted directories only
    ("/etc", "system", True),
    ("/var/lib", "system", True),
    ("/opt", "system", True),
)

#: Directories that belong to the desktop, the toolkit or the user, and are
#: never attributable to a single application.
