"""Turn a :class:`Plan` into actions, with one authentication prompt.

Design notes:

* Nothing is executed until :func:`execute` is called. ``Plan`` objects are
  inspectable, printable and testable on their own.
* Every privileged step goes into a single generated shell script run once
  through ``pkexec``, so the user types their password once per operation
  instead of once per package.
* Residue paths are re-checked against :mod:`appsweep.safety` immediately
  before deletion, not just when the plan was built — the plan may have been
  sitting on screen for a while.
* ``dry_run`` prints exactly what would run and touches nothing.
"""
from __future__ import annotations

import os
import shlex
import subprocess
import tempfile
from collections.abc import Callable, Iterable

from .leftovers import trash_or_delete
from .models import Plan, Residue
from .safety import Unsafe, check_path, check_shape
from .util import have

Emit = Callable[[str], None]

TRASH_SENTINEL = "__trash__"


class ExecError(Exception):
    pass


def describe(plan: Plan, selected_residues: Iterable[Residue] = ()) -> list[str]:
    """Human readable preview of everything a plan will do."""
    lines: list[str] = []
    for st in plan.steps:
        if st.argv and st.argv[0] == TRASH_SENTINEL:
            lines.append(f"trash  {st.argv[1]}")
        else:
            prefix = "sudo  " if st.needs_root else "      "
            lines.append(prefix + shlex.join(st.argv))
    for r in selected_residues:
        prefix = "sudo  " if r.needs_root else "trash "
        lines.append(f"{prefix} delete {r.path}")
    return lines


def _root_script(commands: list[str]) -> str:
    body = "\n".join(
        [
            "#!/bin/sh",
            "# Generated by AppSweep. Runs once under pkexec.",
            "set -e",
            'export DEBIAN_FRONTEND=noninteractive',
            "",
            *commands,
            "",
            'echo "__APPSWEEP_DONE__"',
        ]
    )
    return body


def execute(
    plan: Plan,
    residues: Iterable[Residue] = (),
    *,
    dry_run: bool = False,
    permanent_delete: bool = False,
    emit: Emit | None = None,
) -> bool:
    """Run ``plan``. Returns True when everything succeeded."""
    out = emit or (lambda s: None)
    residues = list(residues)

    if plan.notes:
        for n in plan.notes:
            out(f"note: {n}")

    # --- split the work ------------------------------------------------
    root_cmds: list[str] = []
    user_steps = []
    for st in plan.steps:
        if st.argv and st.argv[0] == TRASH_SENTINEL:
            user_steps.append(st)
        elif st.needs_root:
            root_cmds.append(_as_sh(st.argv, st.description))
        else:
            user_steps.append(st)

    ok_shape = True
    root_residues: list[Residue] = []
    user_residues: list[Residue] = []
    for r in residues:
        (root_residues if r.needs_root else user_residues).append(r)

    for r in root_residues:
        try:
            check_shape(r.path)
        except Unsafe as exc:
            out(f"refused {r.path}: {exc}")
            ok_shape = False
            continue
        if not os.path.lexists(r.path):
            out(f"already gone: {r.path}")
            continue
        try:
            p = check_path(r.path)
        except Unsafe as exc:
            out(f"refused {r.path}: {exc}")
            continue
        root_cmds.append(
            f'echo ">> removing {shlex.quote(str(p))}"\n'
            f"rm -rf -- {shlex.quote(str(p))}"
        )

    ok = ok_shape

    # --- privileged half ------------------------------------------------
    if root_cmds:
        script = _root_script(root_cmds)
        if dry_run:
            out("--- would run as root via pkexec ---")
            for line in script.splitlines():
                out("  " + line)
        else:
            ok = _run_root(script, out) and ok

    # --- unprivileged half ----------------------------------------------
    for st in user_steps:
        if st.argv and st.argv[0] == TRASH_SENTINEL:
            target = st.argv[1]
            if dry_run:
                out(f"would trash {target}")
                continue
            good, msg = trash_or_delete(target, permanent=permanent_delete)
            out(f"{'ok' if good else 'FAILED'}: {target} — {msg}")
            ok = good and ok
            continue
        if dry_run:
            out("would run: " + shlex.join(st.argv))
            continue
        out("$ " + shlex.join(st.argv))
        ok = _stream(st.argv, out) and ok

    for r in user_residues:
        if dry_run:
            out(f"would {'delete' if permanent_delete else 'trash'} {r.path}")
            continue
        good, msg = trash_or_delete(r.path, permanent=permanent_delete)
        out(f"{'ok' if good else 'FAILED'}: {r.path} — {msg}")
        ok = good and ok

    return ok


def _as_sh(argv: list[str], description: str = "") -> str:
    head = f'echo ">> {description}"\n' if description else ""
    return head + shlex.join(argv)


def _run_root(script: str, out: Emit) -> bool:
    if not have("pkexec") and not have("sudo"):
        out("FAILED: neither pkexec nor sudo is available")
        return False

    fd, path = tempfile.mkstemp(prefix="appsweep-", suffix=".sh")
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(script)
        os.chmod(path, 0o755)
        if have("pkexec"):
            argv = ["pkexec", "/bin/sh", path]
            out("Requesting administrator access…")
        else:
            argv = ["sudo", "-n", "/bin/sh", path]
            out("Running with sudo (needs a cached credential)…")
        good = _stream(argv, out)
        if not good:
            out("The privileged step did not complete.")
        return good
    finally:
        try:
            os.unlink(path)
        except OSError:
            pass


def _stream(argv: list[str], out: Emit) -> bool:
    try:
        proc = subprocess.Popen(
            argv,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
            env={**os.environ, "LC_ALL": "C", "DEBIAN_FRONTEND": "noninteractive"},
        )
    except OSError as exc:
        out(f"FAILED to start {argv[0]}: {exc}")
        return False

    assert proc.stdout is not None
    for line in proc.stdout:
        line = line.rstrip("\n")
        if line == "__APPSWEEP_DONE__":
            continue
        if line:
            out(line)
    code = proc.wait()
    if code != 0:
        out(f"exit status {code}")
    return code == 0
